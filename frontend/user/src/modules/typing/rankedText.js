function buildRankedText() {
  let text = RANKED_TEXT
  // 若源文不足 1500，循环补齐后截断，保证全员同一长度
  while ([...text].length < RANKED_TARGET_CHARS) {
    text += RANKED_TEXT
  }
  return [...text].slice(0, RANKED_TARGET_CHARS).join('')
}

export const RANKED_PRACTICE_TEXT = buildRankedText()

export function getRankedMeta() {
  return {
    mode: 'ranked',
    durationSec: RANKED_DURATION_SEC,
    textVersion: RANKED_TEXT_VERSION,
    targetChars: [...RANKED_PRACTICE_TEXT].length,
    text: RANKED_PRACTICE_TEXT,
  }
}
