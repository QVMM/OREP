OFFICIAL_ITEM_NAMES = tuple(_BANDS.keys())


def band_label(name: str, score) -> str:
    try:
        value = float(score)
    except (TypeError, ValueError):
        return ""
    rows = _BANDS.get(str(name or "").strip()) or []
    if not rows:
        return ""
    chosen = rows[0][2]
    for low, high, label in rows:
        if value + 1e-9 >= low:
            chosen = label
            if value <= high + 1e-9:
                return label
    return chosen
